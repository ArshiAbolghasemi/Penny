"""## 7c. Robustness to noise injected before feature engineering

This experiment now corrupts the **raw resampled Coinbase rows in the chronological
test region**, rather than adding noise to normalized model tensors. Each corruption
case follows the complete deployed data path:

**held-out raw rows → structurally valid raw perturbation → OFI/features → causal
rolling normalization → regenerated labels and test windows → model accuracy**

Training and validation rows are never changed. Label thresholds are still calibrated
from the untouched training region, while labels are deliberately regenerated from the
perturbed test mid-price, as requested. Consequently, this measures prediction of the
**perturbed market path**; the reported label-change rate shows how different that task
is from the clean test task.

Noise severity is measured in multiples of one-step scales estimated only from training
rows. Price severity uses the standard deviation of training log returns after symmetric
0.5% winsorization (so unchanged 10-second bins cannot collapse the scale); size/count
severity uses MAD-based log-increment scales. A common row-wise log-price shock is applied
to every price field, which
preserves the existing bid/ask ordering. Positive amounts and trade counts are perturbed
in log space and remain non-negative. Mid-price, spread, and trade imbalance are then
recomputed before feature engineering.

The four standardized innovation laws are Gaussian, compound-Poisson/Gamma jump,
Student-t (ν=3), and clipped α-stable. The raw input here is the resampled snapshot
parquet, not the original exchange message stream.

"""

from crypto.dataset import LOBDataset, _valid_starts  # noqa: E402
from crypto.labels import build_labels  # noqa: E402
from crypto.loader import _rolling_mean_std  # noqa: E402
from torch.utils.data import Subset  # noqa: E402

