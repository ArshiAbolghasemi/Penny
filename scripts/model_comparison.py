_cap_draw = _positive_stable(_cap_rng, 250_000, beta=ASTABLE_ALPHA / 2.0)
ASTABLE_CAP = float(np.quantile(_cap_draw, ASTABLE_CLIP_Q))
ASTABLE_STD = float(np.sqrt(np.mean(np.minimum(_cap_draw, ASTABLE_CAP))))


def _unit_innovations(rng, shape, kind):
    """Zero-centred, approximately unit-variance innovations for fair severity."""
    if kind == "gaussian":
        return rng.standard_normal(shape)
    if kind == "student_t":
        return rng.standard_t(STUDENT_NU, size=shape) * np.sqrt(
            (STUDENT_NU - 2.0) / STUDENT_NU
        )
    if kind == "jump":
        count = rng.poisson(JUMP["rate"], size=shape)
        jump_var = np.zeros(shape, dtype=np.float64)
        mask = count > 0
        if np.any(mask):
            jump_var[mask] = rng.gamma(count[mask] * JUMP["shape"], JUMP["scale"])
        total_var = 1.0 + jump_var
        expected_var = 1.0 + JUMP["rate"] * JUMP["shape"] * JUMP["scale"]
        return rng.standard_normal(shape) * np.sqrt(total_var / expected_var)
    if kind == "alpha_stable":
        A = _positive_stable(rng, shape, beta=ASTABLE_ALPHA / 2.0)
        A = np.minimum(A, ASTABLE_CAP)
        return rng.standard_normal(shape) * np.sqrt(A) / ASTABLE_STD
    raise ValueError(f"unknown corruption kind {kind!r}")


