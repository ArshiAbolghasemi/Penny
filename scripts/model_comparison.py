def _select_test_subset(ds, y, k):
    """Use every test window unless ROBUST_MAX_WINDOWS explicitly requests a cap."""
    if ROBUST_MAX_WINDOWS is None or len(ds) <= ROBUST_MAX_WINDOWS:
        return ds, y
    rng = np.random.default_rng(ROBUST_SEED + k)
    idx = np.sort(rng.choice(len(ds), ROBUST_MAX_WINDOWS, replace=False))
    return Subset(ds, idx.tolist()), y[idx]


@torch.no_grad()
def run_raw_robust_sweep():
    """Accuracy/F1 after raw corruption; keep jump-case probabilities for calibration."""
    rows, probs = [], {}

    for k in HORIZONS:
        cases = {}
        clean_ds, clean_y, clean_meta = raw_test_set(k, "gaussian", 0.0)
        clean_ds, clean_y = _select_test_subset(clean_ds, clean_y, k)

        # Verify that rebuilding the untouched raw path reproduces test labels.
        _, reference_y, _ = test_set(k)
        if ROBUST_MAX_WINDOWS is None:
            if not np.array_equal(clean_y, reference_y):
                raise AssertionError(f"k={k}: raw clean labels do not match test_set()")
        print(f"k={k}: prepared {len(clean_y):,} chronological test windows")

        for kind in ROBUST_KINDS:
            for sigma in ROBUST_SIGMAS:
                ds, y, meta = raw_test_set(k, kind, sigma)
                ds, y = _select_test_subset(ds, y, k)
                if len(y) != len(clean_y):
                    raise AssertionError(
                        f"k={k}, {kind}, sigma={sigma}: test-window count changed"
                    )
                cases[(kind, sigma)] = (
                    ds,
                    y,
                    float(np.mean(y != clean_y)),
                    _case_distortion(kind, sigma),
                )

        for tag in MODELS:
            path = CHECKPOINTS.get(tag, {}).get(k)
            if not path or not Path(path).exists():
                continue
            model = build_model(tag, load_ckpt(path))
            prediction_cache = {}

            for kind in ROBUST_KINDS:
                for sigma in ROBUST_SIGMAS:
                    cache_key = ("clean", 0.0) if sigma == 0.0 else (kind, sigma)
                    ds, expected_y, label_change, distortion = cases[(kind, sigma)]
                    if cache_key not in prediction_cache:
                        prediction_cache[cache_key] = evaluate(model, ds)
                    yt, yp, pr = prediction_cache[cache_key]
                    if not np.array_equal(yt, expected_y):
                        raise AssertionError(
                            "dataset labels and evaluation labels differ"
                        )

                    rows.append(
                        {
                            "model": DISPLAY[tag],
                            "k": k,
                            "kind": kind,
                            "sigma": sigma,
                            **distortion,
                            "accuracy": float(np.mean(yt == yp)),
                            "macro_f1": f1_score(
                                yt,
                                yp,
                                average="macro",
                                labels=[0, 1, 2],
                                zero_division=0,
                            ),
                            "label_change_rate": label_change,
                        }
                    )
                    if kind == "jump" and abs(sigma - SIGMA_FOCUS) < 1e-12:
                        probs[(tag, k)] = (yt, yp, pr)

            del model
            if DEVICE.type == "cuda":
                torch.cuda.empty_cache()

        n_models = len({r["model"] for r in rows if r["k"] == k})
        print(f"  evaluated {n_models} models")

    return pd.DataFrame(rows), probs


