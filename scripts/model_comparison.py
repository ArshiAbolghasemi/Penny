ROBUST_MAX_WINDOWS = None
ROBUST_SIGMAS = [0.0, 0.5, 1.0, 2.0, 4.0]
ROBUST_KINDS = ["gaussian", "jump", "student_t", "alpha_stable"]
SIGMA_FOCUS = 1.0
ROBUST_SEED = 20260802

