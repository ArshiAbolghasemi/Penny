STUDENT_NU = 3.0
ASTABLE_ALPHA = 1.7
ASTABLE_CLIP_Q = 0.999


def _robust_std(x, fallback=1.0):
    """MAD-based scale, with an ordinary-std fallback for nearly constant series."""
    x = np.asarray(x, dtype=np.float64)
    x = x[np.isfinite(x)]
    if len(x) == 0:
        return float(fallback)
    med = np.median(x)
    scale = np.median(np.abs(x - med)) / 0.6744897501960817
    if not np.isfinite(scale) or scale < 1e-12:
        scale = np.std(x)
    return float(scale if np.isfinite(scale) and scale >= 1e-12 else fallback)


def _positive_stable(rng, shape, beta):
    """Positive beta-stable draws using Kanter's construction."""
    U = rng.uniform(1e-7, np.pi - 1e-7, size=shape)
    E = np.maximum(rng.exponential(size=shape), 1e-12)
    term1 = np.sin(beta * U) / np.maximum(np.sin(U), 1e-12) ** (1.0 / beta)
    term2 = np.maximum(np.sin((1.0 - beta) * U) / E, 1e-30) ** ((1.0 - beta) / beta)
    return np.maximum(term1 * term2, 1e-12)


# A single fixed truncation and normalization, not a batch-dependent test statistic.
