def _corrupt_test_rows(kind, sigma):
    """Copy raw data and perturb only rows belonging to the held-out test region."""
    df = _RAW_DF.copy()
    if sigma == 0.0:
        return df

    seed = ROBUST_SEED + 100_003 * ROBUST_KINDS.index(kind) + int(round(10_000 * sigma))
    rng = np.random.default_rng(seed)
    n_test = _RAW_N - _RAW_TEST_START
    test_slice = slice(_RAW_TEST_START, _RAW_N)

    # One price shock per timestamp, shared by every price level/field. This keeps
    # the original book ordering and relative tick geometry intact.
    price_z = _unit_innovations(rng, n_test, kind)
    log_price_shock = sigma * RAW_PRICE_STEP * price_z
    log_price_shock = np.clip(log_price_shock, -0.25, 0.25)
    price_factor = np.exp(log_price_shock)
    for col in _RAW_PRICE_COLS:
        values = pd.to_numeric(df[col], errors="coerce").to_numpy(np.float64)
        values[test_slice] = values[test_slice] * price_factor
        df[col] = values

    # Sizes remain non-negative. Structural zeros remain zero rather than becoming
    # artificial orders/trades.
    for col in _RAW_SIZE_COLS:
        values = pd.to_numeric(df[col], errors="coerce").to_numpy(np.float64)
        current = values[test_slice].copy()
        positive = np.isfinite(current) & (current > 0.0)
        z = _unit_innovations(rng, n_test, kind)
        log_value = np.log1p(np.maximum(current[positive], 0.0))
        log_value = np.maximum(
            log_value + sigma * RAW_SIZE_STEP[col] * z[positive], 0.0
        )
        current[positive] = np.expm1(np.minimum(log_value, 30.0))
        values[test_slice] = current
        df[col] = values

    count = pd.to_numeric(df["trade_count"], errors="coerce").to_numpy(np.float64)
    current = count[test_slice].copy()
    positive = np.isfinite(current) & (current > 0.0)
    z = _unit_innovations(rng, n_test, kind)
    log_count = np.log1p(np.maximum(current[positive], 0.0))
    log_count = np.maximum(log_count + sigma * RAW_COUNT_STEP * z[positive], 0.0)
    current[positive] = np.rint(np.expm1(np.minimum(log_count, 20.0)))
    count[test_slice] = current
    df["trade_count"] = count

    # Rebuild dependent raw fields before feature and label construction.
    bid0 = df["bids[0].price"].to_numpy(np.float64)
    ask0 = df["asks[0].price"].to_numpy(np.float64)
    df["mid"] = (bid0 + ask0) / 2.0
    df["spread"] = ask0 - bid0
    buy = np.maximum(df["buy_vol"].to_numpy(np.float64), 0.0)
    sell = np.maximum(df["sell_vol"].to_numpy(np.float64), 0.0)
    df["trade_imbalance"] = (buy - sell) / (buy + sell + 1e-12)
    return df


def _test_features_from_raw(df, cfg):
    """Recompute raw OFI/features and exact causal normalization for test rows."""
    norm_window = int(cfg.get("norm_window", 2000))

    # One preceding row is needed to compute OFI/returns correctly at the start of
    # the normalization context. It is discarded before rolling statistics.
    context_lo = max(0, _RAW_TEST_START - norm_window)
    extract_lo = max(0, context_lo - 1)
    tail = df.iloc[extract_lo:].copy()

    blocks = []
    for _, day_df in tail.groupby("_date", sort=True):
        blocks.append(extract_features(day_df.reset_index(drop=True), cfg))
    raw_ext = np.concatenate(blocks, axis=0).astype(np.float64)
    raw_context = raw_ext[context_lo - extract_lo :]

    mean, std, count = _rolling_mean_std(raw_context, norm_window)
    std = np.where((count < 2) | (std < 1e-8), 1.0, std)
    normalized = ((raw_context - mean) / std).astype(np.float32)
    test_offset = _RAW_TEST_START - context_lo
    return normalized[test_offset:]


_RAW_CASE_CACHE = {}


def _raw_case(kind, sigma):
    """Return corrupted test features and full mid path, cached across horizons."""
    key = ("clean", 0.0) if sigma == 0.0 else (kind, float(sigma))
    if key not in _RAW_CASE_CACHE:
        noisy = _corrupt_test_rows(kind, sigma)
        _RAW_CASE_CACHE[key] = {
            "features": _test_features_from_raw(noisy, _RAW_CFG),
            "mid": noisy["mid"].to_numpy(np.float64),
        }
    return _RAW_CASE_CACHE[key]


def _case_distortion(kind, sigma):
    """Measured distortion on normalized test features, comparable across laws."""
    clean = _raw_case("gaussian", 0.0)["features"].astype(np.float64)
    noisy = _raw_case(kind, sigma)["features"].astype(np.float64)
    delta = noisy - clean
    rel_l2 = np.linalg.norm(delta) / max(np.linalg.norm(clean), 1e-12)
    clean_mad = np.median(
        np.abs(clean - np.median(clean, axis=0, keepdims=True)), axis=0
    )
    delta_mad = np.median(np.abs(delta), axis=0)
    mad_ratio = np.nanmedian(delta_mad / np.maximum(clean_mad, 1e-12))
    q_clean = np.nanquantile(np.abs(clean), 0.95, axis=0)
    q_delta = np.nanquantile(np.abs(delta), 0.95, axis=0)
    q95_ratio = np.nanmedian(q_delta / np.maximum(q_clean, 1e-12))
    abnormal_move_prob = float(
        np.mean(np.abs(delta) > np.nanquantile(np.abs(clean), 0.99))
    )
    return {
        "distortion_l2": float(rel_l2),
        "distortion_mad": float(mad_ratio),
        "distortion_q95": float(q95_ratio),
        "abnormal_move_prob": abnormal_move_prob,
    }


def raw_test_set(k, kind, sigma):
    """Build a test dataset after raw corruption, feature extraction, and labeling."""
    cfg = json.loads((REPO / DATA_CONFIG.format(fm=FEATURE_MODE, k=k)).read_text())
    case = _raw_case(kind, sigma)
    labels, alpha = build_labels(case["mid"], cfg, _RAW_TRAIN_END)
    starts = _valid_starts(
        _RAW_TEST_START,
        _RAW_N,
        cfg["T_past"],
        cfg["label_k"],
        labels,
        _RAW_TS,
        cfg["stride"],
    )
    starts_rel = starts - _RAW_TEST_START
    labels_test = labels[_RAW_TEST_START:]
    ds = LOBDataset(case["features"], starts_rel, labels_test, cfg["T_past"])
    y = labels[starts + cfg["T_past"] - 1]
    return ds, y, {"alpha": alpha, "starts": starts}


"""### 7d. Real market stress tests

Synthetic corruption is only one robustness view. This table uses the uncorrupted
BTCIRT test period and slices windows by observed market stress regimes: high
realized volatility, spread widening, liquidity drops, abnormal OFI bursts, and
timestamp gaps that proxy exchange/data outages. Each regime is selected from the
top or bottom decile within the same horizon, except exchange gaps, which are
reported only where a real gap is present.
"""


def _window_apply(starts, width, values, func):
    values = np.asarray(values, dtype=np.float64)
    return np.asarray([func(values[s : s + width]) for s in starts], dtype=np.float64)


def _real_stress_scores(k):
    cfg = json.loads((REPO / DATA_CONFIG.format(fm=FEATURE_MODE, k=k)).read_text())
    _, y, meta = raw_test_set(k, "gaussian", 0.0)
    starts = meta["starts"]
    width = int(cfg["T_past"])

    mid = np.maximum(_RAW_DF["mid"].to_numpy(np.float64), 1e-12)
    log_mid = np.log(mid)
    spread = np.maximum(_RAW_DF["spread"].to_numpy(np.float64), 0.0) / mid

    bid_amt = _RAW_DF.get("bids[0].amount", pd.Series(0.0, index=_RAW_DF.index))
    ask_amt = _RAW_DF.get("asks[0].amount", pd.Series(0.0, index=_RAW_DF.index))
    top_depth = np.maximum(
        pd.to_numeric(bid_amt, errors="coerce").to_numpy(np.float64), 0.0
    ) + np.maximum(pd.to_numeric(ask_amt, errors="coerce").to_numpy(np.float64), 0.0)

    buy = np.maximum(_RAW_DF["buy_vol"].to_numpy(np.float64), 0.0)
    sell = np.maximum(_RAW_DF["sell_vol"].to_numpy(np.float64), 0.0)
    ofi_burst = np.abs(buy - sell) / (buy + sell + 1e-12)

    ts = _RAW_DF["bin"].to_numpy(np.int64)
    dt = np.diff(ts, prepend=ts[0])
    ordinary_dt = np.median(dt[dt > 0]) if np.any(dt > 0) else 0

    scores = {
        "high_volatility": _window_apply(
            starts, width + 1, log_mid, lambda x: np.std(np.diff(x))
        ),
        "spread_widening": _window_apply(starts, width, spread, np.nanmean),
        "liquidity_drop": -_window_apply(starts, width, top_depth, np.nanmean),
        "abnormal_ofi_burst": _window_apply(starts, width, ofi_burst, np.nanmax),
    }
    if ordinary_dt > 0:
        scores["exchange_gap"] = _window_apply(
            starts, width, dt, lambda x: np.max(x) > 1.5 * ordinary_dt
        )
    else:
        scores["exchange_gap"] = np.zeros(len(starts), dtype=bool)
    return y, scores


def _mask_from_score(score, q=0.90):
    score = np.asarray(score)
    if score.dtype == bool:
        return score
    finite = np.isfinite(score)
    if not np.any(finite):
        return np.zeros(len(score), dtype=bool)
    thr = np.quantile(score[finite], q)
    return finite & (score >= thr)


