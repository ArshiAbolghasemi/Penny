def plot_calibration_under_noise(k, n_bins=10):
    tags = [tag for tag in MODELS if (tag, k) in ROBUST_PROBS]
    if not tags:
        return

    cmap = plt.get_cmap("tab10")
    fig, ax = plt.subplots(figsize=(6.2, 5))
    for i, tag in enumerate(tags):
        yt, yp, probabilities = ROBUST_PROBS[(tag, k)]
        confidence = probabilities.max(1)
        correct = (yt == yp).astype(float)
        edges = np.quantile(confidence, np.linspace(0, 1, n_bins + 1))
        edges[-1] += 1e-9
        bin_id = np.clip(np.digitize(confidence, edges) - 1, 0, n_bins - 1)
        mean_confidence = [
            confidence[bin_id == b].mean() if np.any(bin_id == b) else np.nan
            for b in range(n_bins)
        ]
        mean_accuracy = [
            correct[bin_id == b].mean() if np.any(bin_id == b) else np.nan
            for b in range(n_bins)
        ]
        ece = np.nansum(
            [
                np.mean(bin_id == b)
                * abs(
                    np.nan_to_num(mean_accuracy[b]) - np.nan_to_num(mean_confidence[b])
                )
                for b in range(n_bins)
            ]
        )
        ax.plot(
            mean_confidence,
            mean_accuracy,
            "o-",
            ms=4,
            color=cmap(i % 10),
            label=f"{DISPLAY[tag]} (ECE={ece:.3f})",
        )

    ax.plot([1 / 3, 1], [1 / 3, 1], "k--", lw=0.8, alpha=0.6)
    ax.set_xlabel("mean confidence (p_max)")
    ax.set_ylabel("accuracy")
    jump_d = _case_distortion("jump", SIGMA_FOCUS)["distortion_l2"]
    ax.set_title(f"Reliability after raw jump corruption (D={jump_d:.3f}) — k={k}")
    ax.legend(fontsize=7)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    save_fig(fig)
    plt.show()


