def _fig_slug(fig) -> str:
    """Filename stem derived from the figure's own title.

    Most plots here are drawn inside a loop and title themselves with the loop
    variable (``f"... k={k}"``), so slugging the *rendered* title is what keeps
    the per-iteration PDFs from overwriting each other.
    """
    get = getattr(fig, "get_suptitle", None)
    text = get() if callable(get) else ""
    if not text and fig.axes:
        text = " ".join(a.get_title() for a in fig.axes if a.get_title())
    slug = "".join(c if (c.isascii() and c.isalnum()) else "_" for c in text.lower())
    while "__" in slug:
        slug = slug.replace("__", "_")
    return slug.strip("_")[:70] or "figure"


def save_fig(fig, name: str | None = None) -> Path:
    """Write `fig` to ``FIG_DIR`` as a vector PDF; returns the path.

    Repeated stems get a numeric suffix so two different figures that happen to
    share a title never clobber one another. The counter lives in the kernel, so
    a clean top-to-bottom run always writes the unsuffixed names; re-running one
    cell mid-session appends ``_2``, ``_3``, … instead of overwriting.
    """
    stem = name or _fig_slug(fig)
    seen = _FIG_SEEN[stem] = _FIG_SEEN.get(stem, 0) + 1
    out = FIG_DIR / (f"{stem}.pdf" if seen == 1 else f"{stem}_{seen}.pdf")
    fig.savefig(out, bbox_inches="tight")
    print(f"saved → {out.relative_to(REPO)}")
    return out


